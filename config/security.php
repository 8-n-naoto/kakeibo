<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Content-Security-Policy を強制するか
    |--------------------------------------------------------------------------
    |
    | false の間は Content-Security-Policy-Report-Only で送るので、違反は
    | ブラウザのコンソールに出るだけで画面は壊れない。
    | 全画面（ダッシュボードのグラフ、レシート読み取り、CSV取込プレビュー）を
    | 開いてコンソールに違反が出ないことを確かめてから true にする。
    |
    */

    'csp_enforce' => (bool) env('CSP_ENFORCE', false),

    /*
    |--------------------------------------------------------------------------
    | HSTS
    |--------------------------------------------------------------------------
    |
    | https で応答したときだけ送る。家庭内LANの http 運用では意味が無いので既定は false。
    | 一度でも送ると、そのブラウザは max-age の間 http でアクセスできなくなるので、
    | 証明書の運用を決めてから有効にすること。
    |
    */

    'hsts' => (bool) env('HSTS_ENABLED', false),

    'hsts_max_age' => (int) env('HSTS_MAX_AGE', 31536000),

];
